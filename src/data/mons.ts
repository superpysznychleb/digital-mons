export function getMonById(id: string): Mon | undefined {
  return ALL_MONS.find((m) => m.id === id);
}

export function getMonsByStage(stage: Mon["stage"]): Mon[] {
  return ALL_MONS.filter((m) => m.stage === stage);
}

export function getEvolutionChain(monId: string): Mon[] {
  const chain = EVOLUTION_CHAINS.find((c) => c.stages.includes(monId));
  if (!chain) return [];
  return chain.stages.map((id) => getMonById(id)!);
}
